"""Generate site/js/pdf-fonts.js: glyph widths of the standard PDF fonts.

Widths come from the Adobe Font Metrics bundled with reportlab, for the
WinAnsi (cp1252) code points 32-255 that site/js/pdf.js can draw.
    python scripts/gen_pdf_fonts.py
"""
import json
import os

from reportlab.pdfbase.pdfmetrics import stringWidth

FONTS = ("Times-Roman", "Times-Bold", "Helvetica", "Helvetica-Bold")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    widths = {}
    for font in FONTS:
        row = []
        for code in range(32, 256):
            try:
                ch = bytes([code]).decode("cp1252")
            except UnicodeDecodeError:
                row.append(0)
                continue
            row.append(round(stringWidth(ch, font, 1000)))
        widths[font] = row
    path = os.path.join(ROOT, "site", "js", "pdf-fonts.js")
    with open(path, "w") as f:
        f.write("// Generated by scripts/gen_pdf_fonts.py: widths (1/1000 em) of WinAnsi codes 32-255.\n")
        f.write("(function (root) {\n  var W = " + json.dumps(widths, separators=(",", ":")) + ";\n")
        f.write("  if (typeof module !== 'undefined' && module.exports) module.exports = W;\n")
        f.write("  else root.PdfFontWidths = W;\n")
        f.write("})(this);\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
